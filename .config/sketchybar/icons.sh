# The glyphs are written as UTF-8 byte escapes so this file stays plain ASCII:
# private-use characters can't be mangled by an editor, a terminal font or a
# copy/paste, and a missing glyph can be traced to its exact codepoint.
# Every codepoint below exists in Nerd Fonts v3. The old v2 "Material Design"
# range (U+F500-U+FD46, e.g. the previous mute icon U+FC5D) was removed in v3,
# which is why some icons rendered as blanks/boxes.
# Look names up at https://www.nerdfonts.com/cheat-sheet

